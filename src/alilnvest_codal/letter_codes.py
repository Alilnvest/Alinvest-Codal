def canonical_letter_code(letter_code: str | None) -> str | None:
    """کد را مستقل از فاصله، نوع خط تیره و ارقام فارسی/عربی به شکل رسمی برمی‌گرداند."""
    if letter_code is None:
        return None
    text = str(letter_code).strip().translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789"))
    text = re.sub(r"\s+", "", text).replace("‐", "-").replace("‑", "-").replace("–", "-").replace("—", "-")
    match = re.fullmatch(r"ن[-]?0*(\d+)", text, flags=re.IGNORECASE)
    return f"ن-{int(match.group(1))}" if match else text


def describe_letter_code(letter_code: str | None) -> str | None:
    """توضیحِ فارسیِ یه letter_code («ن-XX»)؛ اگه کد ناشناخته بود None برمی‌گردونه."""
    if not letter_code:
        return None
    return LETTER_CODES.get(canonical_letter_code(letter_code))
